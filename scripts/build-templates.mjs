/**
 * Compile templates/*.ejs into a plain TypeScript module.
 *
 * Cloudflare Workers refuse runtime code generation, so EJS cannot compile a
 * template string on the edge. We therefore take EJS's generated function body
 * at build time and wrap it in an ordinary exported function; the deployed
 * Worker never calls eval and never bundles EJS itself.
 *
 * Run with `pnpm build:templates` (also runs before dev, test and deploy).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import ejs from 'ejs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const templateDir = join(root, 'templates');
const outFile = join(root, 'src', 'render', 'templates.generated.ts');
const iconFile = join(root, 'assets', 'icon.svg');
const faviconFile = join(root, 'assets', 'favicon.ico');

/** `post.ejs` -> `renderPostTemplate` */
const exportName = (file) =>
  `render${basename(file, '.ejs').replace(/(^|-)([a-z])/g, (_, __, char) => char.toUpperCase())}Template`;

const indent = (source) =>
  source
    .split('\n')
    .map((line) => (line.trim() ? `  ${line.trim()}` : ''))
    .filter(Boolean)
    .join('\n');

function compile(file) {
  const template = new ejs.Template(readFileSync(join(templateDir, file), 'utf8'), {
    client: true,
    strict: true,
    localsName: 'it',
    rmWhitespace: true,
    // Drops EJS's __line bookkeeping and try/catch wrapper from the output.
    compileDebug: false,
    _with: false,
  });
  template.generateSource();
  return `export function ${exportName(file)}(it: TemplateLocals, escapeFn: EscapeFn): string {
  let __output = '';
  const __append = (value: unknown): void => {
    if (value !== undefined && value !== null) __output += String(value);
  };
${indent(template.source)}
  return __output;
}`;
}

const files = readdirSync(templateDir)
  .filter((file) => file.endsWith('.ejs'))
  .sort();

const banner = `// Generated by scripts/build-templates.mjs from templates/*.ejs - do not edit.
// Run \`pnpm build:templates\` after changing a template.
/* eslint-disable */

type EscapeFn = (value: unknown) => string;
/** Templates are handed a view model built in src/render/embed.ts. */
type TemplateLocals = Record<string, any>;
`;

/** Both icons ship inside the bundle so the files in assets/ stay the only copies. */
const icon = [
  `export const ICON_SVG = ${JSON.stringify(readFileSync(iconFile, 'utf8').trim())};`,
  `export const FAVICON_ICO_BASE64 = ${JSON.stringify(readFileSync(faviconFile).toString('base64'))};`,
].join('\n\n');

writeFileSync(outFile, `${banner}\n${icon}\n\n${files.map(compile).join('\n\n')}\n`);
console.log(`compiled ${files.length} template(s) -> ${relative(root, outFile)}`);
